import { createHash } from "node:crypto";
import { constants } from "node:fs";
import { lstat, open } from "node:fs/promises";
import { join } from "node:path";
import { isActor, isIsoInstant, OkfParseError, parse } from "../okf/document.ts";
import { assertConceptPathSpelling, idToAbsPath, InvalidIdError, validateId } from "../okf/paths.ts";
import { checkPrivacyPath, PrivacyPathError } from "../okf/privacy.ts";
import { writeConcept } from "../okf/write.ts";
import type { Citation } from "./ask.ts";

const ANSWERS = "db_only/answers";
const MAX_DRAFT_HEADER = 2 * 1024 * 1024;

/** This payload comes from a completed answer authenticated by the local Ask adapter. */
export interface AskDraftInput {
  receiptId: string;
  generatedAt: string;
  question: string;
  answer: string;
  provider: string;
  model: string;
  citations: readonly Citation[];
  /** A successful prior save can be retried, but a removed draft must not be recreated. */
  mustExist?: boolean;
}

export interface AskDraftResult {
  id: string;
  created: boolean;
}

export class AskDraftError extends Error {
  constructor(message: string, readonly status: 400 | 409 | 410) { super(message); }
}

function conflict() {
  return new AskDraftError("The private draft path is occupied or the saved draft changed.", 409);
}

const absent = (error: NodeJS.ErrnoException) => {
  if (error.code !== "ENOENT") throw error;
  return undefined;
};

function cite(citation: Citation) {
  validateId(citation.id);
  return {
    resource: `/${citation.id.split("/").map(encodeURIComponent).join("/")}.md`,
    title: citation.title,
  };
}

async function readDraftMarker(path: string) {
  const file = await open(path, constants.O_RDONLY | (constants.O_NOFOLLOW ?? 0) | (constants.O_NONBLOCK ?? 0)).catch(absent);
  if (!file) return;
  try {
    const info = await file.stat();
    if (!info.isFile() || info.size === 0) throw conflict();
    const header = Buffer.alloc(Math.min(info.size, MAX_DRAFT_HEADER));
    const { bytesRead } = await file.read(header, 0, header.length, 0);
    return parse(header.subarray(0, bytesRead).toString("utf8")).frontmatter.ask_receipt ?? null;
  } catch (error) {
    if (error instanceof OkfParseError) throw conflict();
    throw error;
  } finally {
    await file.close();
  }
}

/** Save the completed answer through the normal OKF writer, with no model or retrieval call. */
export async function saveAskDraft(root: string, draft: AskDraftInput, authorize?: () => void): Promise<AskDraftResult> {
  const { receiptId, question, answer, provider, model, generatedAt } = draft;
  if (!/^[a-f0-9]{32}$/.test(receiptId) || !isIsoInstant(generatedAt) || !generatedAt.endsWith("Z") ||
      !question.trim() || !answer.trim() || !provider.trim() || !model.trim())
    throw new AskDraftError("Only a completed answer can be saved as a private draft.", 400);

  const id = `${ANSWERS}/${receiptId}`;
  const path = idToAbsPath(root, id);
  let sources;
  try {
    sources = draft.citations.map(cite);
  } catch (error) {
    if (error instanceof InvalidIdError || error instanceof URIError)
      throw new AskDraftError("The completed answer has an invalid note citation.", 400);
    throw error;
  }
  const label = `${provider}/${model}`;
  const by = isActor(label) && !/[\x00-\x1f\x7f]/.test(label)
    ? label
    : `${encodeURIComponent(provider.toWellFormed())}/${encodeURIComponent(model.toWellFormed())}`;
  const fingerprint = createHash("sha256").update(JSON.stringify([
    "okbrain/ask-draft/v1", receiptId, generatedAt, question, answer, provider, model, sources,
  ])).digest("hex");
  const marker = { id: receiptId, provider, model, fingerprint };
  const body = `## Question\n\n${question}\n\n## Answer\n\n${answer}`;

  const checkPath = async () => {
    try {
      await assertConceptPathSpelling(root, id);
      await checkPrivacyPath(root, id);
    } catch (error) {
      if (error instanceof InvalidIdError || error instanceof PrivacyPathError) throw conflict();
      throw error;
    }
  };
  await checkPath();
  if (!draft.mustExist && !await lstat(path).catch(absent)) {
    const title = Array.from(question.replace(/[\s\p{Cc}]+/gu, " ").trim()).slice(0, 100).join("") || "Ask answer";
    const written = await writeConcept(root, {
      id,
      type: "note",
      title,
      description: "Answer generated from this brain.",
      tags: ["inbox", "ask"],
      status: "draft",
      generated: { by, at: generatedAt },
      body,
      sources,
      extra: { db_only: true, ask_receipt: marker },
    }, {
      createOnly: true,
      authorize: async () => {
        await checkPath();
        // These indexes are generated by the OKF writer. Keep private listings off aliased paths.
        for (const directory of [root, join(root, "db_only"), join(root, "db_only", "answers")]) {
          const info = await lstat(join(directory, "index.md")).catch(absent);
          if (info && (!info.isFile() || info.nlink > 1)) throw conflict();
        }
        authorize?.();
      },
    });
    if (written.created) return { id, created: true };
  }

  await checkPath();
  const saved = await readDraftMarker(path) as Partial<typeof marker> | null | undefined;
  if (saved === undefined) throw new AskDraftError("The saved private draft was removed. Ask again to create a new draft.", 410);
  if (saved?.id !== receiptId || saved.provider !== provider || saved.model !== model || saved.fingerprint !== fingerprint)
    throw conflict();
  return { id, created: false };
}
